check('printer/parser roundtrip',()=>{for(const s of ['λx.x','λx.x x0','λx.λx.x','λx.λy.x y','a (λb.c b)'])assert(C.alphaEqual(C.parse(s),C.parse(C.print(C.parse(s)))));});
check('末尾構文・不正トークンの拒否',()=>{for(const s of ['x )','λx.x . y','x = y','λx.x @','1#','12abc','(x','λx.','x λy.y','λx y.x',''])assert.throws(()=>C.parse(s),s);});
