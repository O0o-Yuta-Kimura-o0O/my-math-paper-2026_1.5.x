const context=vm.createContext({setTimeout});vm.runInContext(source,context,{timeout:1000});
const C=context.LambdaCore;let checks=0;
function check(label,run){run();checks++;console.log('ok',label);}
async function run(label,source,expected,options={}){
  const result=await C.evaluate(source,options);assert.equal(result.status,'normal-form',result.error);
  assert.equal(C.alphaEqual(result.term,C.parse(expected)),true,label+': '+C.print(result.term));
  const verified=C.verifyTrace(JSON.parse(JSON.stringify(result.trace)));assert.equal(verified.valid,true,verified.error);
  checks++;console.log('ok',label);return result;
}
